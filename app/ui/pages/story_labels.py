def is_hidden(key):
    """内部字段（编号、向量、原始载荷等）不展示，与控制面板一致。"""
    return str(key) in HIDDEN


def label(key):
    """字段名 → 中文标签。未知字段回退为“补充信息”，绝不显示原始字段名。"""
    key = str(key)
    if key in LABELS:
        return LABELS[key]
    if key in GROUPS:
        return GROUPS[key]
    if key and '\u4e00' <= key[0] <= '\u9fff':
        return key
    return '补充信息'


def fmt_time(value):
    """MM-DD HH:MM，本地时区，与控制面板 fmtTime（new Date + 本地取值）一致。"""
    try:
        stamp = _datetime.fromisoformat(str(value).replace('Z', '+00:00'))
    except (TypeError, ValueError):
        return str(value)
    if stamp.tzinfo is not None:
        stamp = stamp.astimezone()
    return f'{stamp.month:02d}-{stamp.day:02d} {stamp.hour:02d}:{stamp.minute:02d}'


def display_value(value, key=''):
    """枚举值 → 中文说明，与控制面板 hValue 一致。"""
    if value is None:
        return '—'
    if isinstance(value, bool):
        return '是' if value else '否'
    if isinstance(value, str):
        if key == 'timezone' and value == 'Asia/Shanghai':
            return '北京时间（上海）'
        if key == 'reviewReason' and value == 'Daily review found no schedule-changing evidence.':
            return '每日检查未发现需要调整日程的依据。'
        if key.endswith(_TIME_KEY) and len(value) >= 10 and value[4] == '-' and value[7] == '-':
            return fmt_time(value)
        if key == 'status' and value == 'active':
            return '生效中'
        if key in _VALUE_KEYS:
            if value in KINDS:
                return KINDS[value]
            if value in VALUES:
                return VALUES[value]
            if '\u4e00' <= value[0] <= '\u9fff':
                return value
            return '其他'
        if key == 'path':
            return ' · '.join(label(part) for part in value.split('.'))
    return value


def clean_description(text):
    """与控制面板 hDescription 相同的术语替换。"""
    if not text:
        return ''
    for source, target in (
        ('Embedding', '记忆检索向量'), ('Preplan', '日程预规划'), ('Console', '管理面板'),
        ('cache-first', '缓存优先'), ('round-robin', '轮流选择'), ('priority', '按顺序优先选择'),
        ('top-p', '候选表达范围'), ('Urge', '主动联系意愿'), ('Alter', '情绪变化值'),
    ):
        text = text.replace(source, target)
    return text
